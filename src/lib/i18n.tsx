export function resolveLanguage(preference: LanguagePreference): AppLanguage {
  if (preference === "zh-CN" || preference === "en-US") return preference;
  const browserLanguage = typeof navigator === "undefined" ? "zh-CN" : navigator.language;
  return browserLanguage.toLocaleLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

export function translate(
  source: string,
  language: AppLanguage,
  values: Record<string, string | number> = {},
): string {
  const template = language === "en-US" ? english[source] || source : source;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

function initialPreference(): LanguagePreference {
  if (typeof localStorage === "undefined") return "system";
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "zh-CN" || stored === "en-US" || stored === "system" ? stored : "system";
}

interface I18nContextValue {
  preference: LanguagePreference;
  language: AppLanguage;
  setPreference: (preference: LanguagePreference) => void;
  t: (source: string, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  preference: "system",
  language: "zh-CN",
  setPreference: () => undefined,
  t: (source, values) => translate(source, "zh-CN", values),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [preference, setPreferenceState] = useState<LanguagePreference>(initialPreference);
  const [systemLanguage, setSystemLanguage] = useState<AppLanguage>(() =>
    resolveLanguage("system"),
  );
  const language = preference === "system" ? systemLanguage : preference;
  const setPreference = useCallback((next: LanguagePreference) => {
    setPreferenceState(next);
    localStorage.setItem(STORAGE_KEY, next);
  }, []);
  const t = useCallback(
    (source: string, values?: Record<string, string | number>) =>
      translate(source, language, values),
    [language],
  );

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    const handleLanguageChange = () => setSystemLanguage(resolveLanguage("system"));
    window.addEventListener("languagechange", handleLanguageChange);
    return () => window.removeEventListener("languagechange", handleLanguageChange);
  }, []);

  const value = useMemo(
    () => ({ preference, language, setPreference, t }),
    [language, preference, setPreference, t],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
